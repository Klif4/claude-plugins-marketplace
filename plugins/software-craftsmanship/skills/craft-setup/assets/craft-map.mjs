#!/usr/bin/env node
// Regenerates `.craft/api-map.d.ts`: the public API of src/domain, signatures only.
//
// The craft loop hands this one file to its agents instead of the list of every
// source file written so far. A fresh agent then learns what exists by reading
// ~1 line per export, rather than by opening forty files — which is what made the
// cost of an iteration grow with the size of the code already written.
//
// It is emitted by `tsc`, so it is extracted from the code and cannot drift.
// Never edit it by hand.
import { spawnSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const DTS = '.craft/dts'
const OUT = '.craft/api-map.d.ts'

// The staging directory is wiped before tsc runs, not only after: a tsc run that
// failed halfway leaves declarations behind, and a later successful run would then
// merge two layouts into one map with duplicated entries.
rmSync(DTS, { recursive: true, force: true })

const tsc = spawnSync('tsc', ['-p', 'tsconfig.map.json'], { encoding: 'utf8', shell: process.platform === 'win32' })
if (tsc.error || tsc.status !== 0) {
  console.error(`${tsc.stdout ?? ''}${tsc.stderr ?? ''}`.trimEnd())
  console.error(tsc.error ? `tsc could not be run: ${tsc.error.message}` : 'tsc -p tsconfig.map.json failed — the map was not regenerated.')
  rmSync(DTS, { recursive: true, force: true })
  process.exit(1)
}

const walk = (directory) =>
  readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry)
    return statSync(path).isDirectory() ? walk(path) : path.endsWith('.d.ts') ? [path] : []
  })

const files = walk(DTS).sort()

const body = files
  .map((file) => {
    const source = `src/domain/${relative(DTS, file).replace(/\.d\.ts$/, '.ts')}`
    return `// ${source}\n${readFileSync(file, 'utf8').trimEnd()}\n`
  })
  .join('\n')

const header = [
  '// GENERATED by `yarn craft:map` — do not edit.',
  '// The public API of src/domain: signatures only, no bodies.',
  '//',
  '// This map tells you WHAT EXISTS, so you can reuse it instead of reinventing it.',
  '// It does not tell you how anything behaves. Before you depend on a contract,',
  '// open the real file named above the declaration.',
  '',
  '',
].join('\n')

const map = header + body

mkdirSync('.craft', { recursive: true })
writeFileSync(OUT, map)
rmSync(DTS, { recursive: true, force: true })

console.log(`${OUT} — ${files.length} domain files, ${map.trimEnd().split('\n').length} lines`)
